    private Vocab() {}

    /** @return the word for an item registry path, or null if that item has no vocabulary entry. */
    public static Word get(Language lang, String itemPath) {
        return WORDS.get(lang).get(itemPath);
    }

    public static boolean has(Language lang, String itemPath) {
        return WORDS.get(lang).containsKey(itemPath);
    }

    public static int size(Language lang) {
        return WORDS.get(lang).size();
    }

    /** A random word out of the given item paths (used for review challenges). Null if the list is empty. */
    public static Word randomOf(Language lang, List<String> itemPaths, Random rng) {
        List<Word> pool = new ArrayList<>();
        for (String p : itemPaths) {
            Word w = get(lang, p);
            if (w != null) pool.add(w);
        }
        return pool.isEmpty() ? null : pool.get(rng.nextInt(pool.size()));
    }
